package com.huawei.mobile.dto;

public class Message {
    private String type;
    private Integer ct;
    private Integer cv;
    private String content;
    private Integer ut;
    private Integer dv;
    private Integer at;
    private String fa;
    private String ga;
    private String cs;

    public String getType() { return type; }
    public void setType(String type) { this.type = type; }
    public Integer getCt() { return ct; }
    public void setCt(Integer ct) { this.ct = ct; }
    public Integer getCv() { return cv; }
    public void setCv(Integer cv) { this.cv = cv; }
    public String getContent() { return content; }
    public void setContent(String content) { this.content = content; }
    public Integer getUt() { return ut; }
    public void setUt(Integer ut) { this.ut = ut; }
    public Integer getDv() { return dv; }
    public void setDv(Integer dv) { this.dv = dv; }
    public Integer getAt() { return at; }
    public void setAt(Integer at) { this.at = at; }
    public String getFa() { return fa; }
    public void setFa(String fa) { this.fa = fa; }
    public String getGa() { return ga; }
    public void setGa(String ga) { this.ga = ga; }
    public String getCs() { return cs; }
    public void setCs(String cs) { this.cs = cs; }
}
